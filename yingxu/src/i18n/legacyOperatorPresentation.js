  const observation=value.last_observation,state={starting:'Starting',running:'Running',destroyed:'Deleted',not_created:'Not created'}[observation?.state],provider={PENDING:'Preparing',FAILED:'Failed',STOPPED:'Stopped',RUNNING:'Running'}[observation?.provider_status];
